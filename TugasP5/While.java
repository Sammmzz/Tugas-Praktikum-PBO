public class While {
    public static void main(String[] args) {
        
        int i = 1;
        int j = 1;
        System.out.println("Looping While menggunakan i++ : ");
        while( i != 5){
            System.out.print(i++ + " ");
        }
        
        System.out.println("");
        System.out.println("Looping While menggunakan ++i : ");
        while( j != 5){
            System.out.print(++j + " ");
        }
        System.out.println("");
    }
}
